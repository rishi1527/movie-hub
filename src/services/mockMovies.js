// Helper function to find a movie by ID across all mock datasets
export const getMovieById = (id) => {
  if (!id) return null;
  const allMovies = [
    ...heroMovies,
    ...trendingMovies,
    ...popularMovies,
    ...popularSeries,
    ...latestReleases,
    ...topRated,
    ...recommended,
    ...Object.values(moodMovies).flat(),
  ];
  return allMovies.find((m) => m.id === id) || null;
};


